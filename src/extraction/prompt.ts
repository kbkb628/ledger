import type { Scene } from "./script.js";

/**
 * 抽取指令 v1 —— 对应 docs/extraction-schema.md 第 7 节的骨架。
 *
 * ## v1 相对 v0 的唯一改动：**把归并拿出去**
 *
 * v0 在 prompt 里附上「已抽出的命题清单」，让模型自己决定 `ref` 是已有 id 还是 `NEW`。
 * 结果模型用**说法相似**当归并依据：一条「苏婉让陈默处理掉沈父留下的那份东西」
 * 吃掉了 F-002/F-005/F-006/F-008/F-009/F-011 六条命题的说法，
 * 因为它们都含「那份东西」（见 docs/test-plan.md §5.1）。
 *
 * v1 因此**只做场内抽取**：模型看不到别的场次，也没有能力跨场归并。
 * 跨场同一性交给独立的归并层（`src/extraction/merge.ts`），
 * 复用判定层那条已经验证到 100% 的路径。
 *
 * 这是设计文档三层路由的原意：
 *   第 0 层抽取（场内）→ 第 1 层结构匹配 → 第 2 层 JEV 判定 → 第 3 层人工
 *
 * ## 最硬的一条约束
 *
 * `surfaces[].text` 必须是**原文里逐字出现的连续片段**。这不是洁癖 ——
 * rsi-log.md 的效度教训里，旧黄金集正是因为混进了「手写的关键词」
 * （剧本里根本没出现）而失真。**指令要求 + 代码校验**双保险。
 *
 * ## v2 的改动：定义粒度
 *
 * v1 的别名去向三分类显示：37 条 golden 别名里真漏抽只有 6 条，
 * **16 条是「抽到了但挂错命题」**，而逐条看几乎全不是错误，是**粒度不一致**：
 *   ·「苏婉伪造并调换了遗嘱」（golden 一条）被拆成「伪造」+「调换」两条
 *   ·「沈知微**知道了**码头那件事」被当成命题 —— 那是知识状态变化
 *   ·「沈知微**说**遗嘱是假的」被当成命题 —— 那是声称，不是事实
 *
 * 所以 v2 把粒度写成可检验的规则：**一条命题 = 一个角色可以知道或不知道的客观事实**。
 * 这正是 R1 判定 `used_at(S,P,C) ∧ P ∉ mind(C)` 需要的粒度 ——
 * `mind(C)` 里的元素必须能被「知道 / 不知道」。
 */
export const EXTRACTION_INSTRUCTIONS = `你是剧本的结构化抽取器。每次收到**一场**剧本。

## 任务
列出**本场**出现的事实性命题，以及本场对每条命题的**指称说法**。

**只考虑本场。** 不要猜测这件事在别的场次有没有出现，也不要给命题编号。

## 什么算一条命题（最重要的一条规则）
**一条命题 = 一个角色「可以知道或不知道」的客观事实。**

检验方法：能不能造出一句合法的「某人不知道这件事」？
- ✅「苏婉伪造了沈父的遗嘱」→ 有人可以不知道 ✔ 是命题
- ✅「沈父真正的遗嘱藏在怀表夹层里」→ 有人可以不知道 ✔ 是命题
- ❌「沈知微知道了码头那件事」→ 这不是事实，是**知识状态的变化**，不是命题
- ❌「沈知微说遗嘱是假的」→ 这是**声称**，不等于事实，不是命题
- ❌「陆见深站在岸边」→ 只是同一件事的一个侧面，没有谁会「不知道」它

**同一次行为的不同侧面算一条命题**，不要拆开：
「苏婉伪造并调换了遗嘱」是**一条**（伪造与调换是同一件事的两面），
不要拆成「苏婉伪造遗嘱」与「苏婉调换遗嘱」。

**不算命题**：环境描写、情绪、纯疑问、常识（「天在下雨」「人终有一死」）、
某人得知/想起/怀疑某事、某人说的话本身。

## canonical —— 命题的规范表述
- 一句话直接描述**这件事本身**，含施事与客体。
- 例：「陆见深三年前在码头与沈父争执，沈父落水，陆见深未施救」。
- 反例：「沈知微提到了码头的事」—— 那是「提及」，不是「命题」。

## surfaces —— 本场对该命题的指称说法（**最重要**）
每条说法是一个对象：\`{"text": "...", "kind": "..."}\`。

- \`text\` 必须是**本场原文里逐字出现的连续片段**，一字不改、不增不减。
- **取能指代它的最短片段，不要整句照抄。** 整句往往太长，别的角色只会用更短的词去提它：
  周管说「真正的那份遗嘱，在书房暗格里」，之后别人只会说「暗格里那份」或「暗格」——
  若你记成整句，那些短引用就对不上了（实测：R1 的召回因此只有 33%）。
  好的例子：「暗格」「那份东西」「两千三百万」「码头那天」「签名是真的」。
- 不要带说话人前缀：写「三年前。我回来了。」而不是「沈知微：三年前。我回来了。」。
- 同一件事在本场有多种说法 → 仍是**一条**命题，surfaces 列全。
- **禁止改写、概括或自己造词。原文没有的说法一律不要写。**
- 没有任何指称说法的命题（纯叙述）→ surfaces 留空数组。

### kind 三选一（判错会让归并层把不同的事并成一条）
- \`"explicit"\` —— **明确指称**：含专名、数字、独特名词。
  例：「两千三百万」「联姻备忘录」「码头那天」
- \`"descriptive"\` —— **描述性指称**：用一整句描述那件事。
  例：「你三年前在码头做了什么」「爸走之前跟我说」
- \`"vague"\` —— **泛化指代**：靠上下文才能定指，脱离上下文什么都不是。
  例：「那件事」「那份东西」「处理掉。烧了」「在。」

## agents —— 做这件事的人（一句话，但很关键）
\`agents\` 是**施事**的人名数组，不是「在场的人」。

- 「苏婉伪造了遗嘱」→ ["苏婉"]
- 「苏婉指使陈默改遗嘱」→ ["苏婉", "陈默"]（共谋者都算）
- 「陈默经手调换了遗嘱」→ ["陈默"]
- 「沈父后退踩空落入水中」→ []（意外，没有施事）
- 「苏婉三年间转走两千三百万」→ ["苏婉"]

⚠️ **只列做这件事的人，不要列仅仅在场或知情的人。**
这个字段只用于一件事：判断某个角色是不是「自己做的事自己知道」。
列错会让审计把真问题当成误报放过。

## knowledge_deltas —— 本场谁得知了什么（与命题分列，互不替代）
另外列出本场发生的**知识变化**：某个角色在本场**得知 / 被告知 / 意识到 / 怀疑**了某件事。

每条是一个对象：\`{"character": "...", "about": "...", "kind": "..."}\`
- \`character\`：剧本里的角色名，逐字照抄。
- \`about\`：**本场原文里指向那件事的连续片段**，逐字不改。
  若原文里找不到能指向它的片段 → **不要记这一条**（宁可漏，不要编）。
- \`kind\`：
  - \`"learns"\` —— 得知了某件真实的事
  - \`"learns_false"\` —— 被告知 / 误以为的是错的事
  - \`"suspects"\` —— 起疑但还不能确定

⚠️ 只记剧本**明确演出**的：被当面告知、亲眼看到、当面承认。
**不要**把「读者能推断出来的」当成「这个角色得知了」——
角色已知的渠道必须发生在剧本里，否则审计会把它误判成知识泄漏。

## 输出
只输出 json，不要任何解释或代码块：
{"propositions":[{"canonical":"...","surfaces":[{"text":"...","kind":"explicit"}],"agents":["..."]}],"knowledge_deltas":[{"character":"...","about":"...","kind":"learns"}]}
本场没有事实性命题时 propositions 为空数组；没有知识变化时 knowledge_deltas 为空数组。`;

export function renderExtractionPrompt(scene: Scene, sceneText: string): string {
  return `${EXTRACTION_INSTRUCTIONS}

---

【本场 ${scene.id} 原文】
${sceneText}`;
}
